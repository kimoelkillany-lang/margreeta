window.genzTranslate = function(lang, path, vars){
  const dict = window.GenZT[lang] || window.GenZT.en;
  const parts = path.split('.');
  let node = dict;
  for (let i = 0; i < parts.length; i++) node = node && node[parts[i]];
  if (node === undefined) {
    let fallback = window.GenZT.en;
    for (let i = 0; i < parts.length; i++) fallback = fallback && fallback[parts[i]];
    node = fallback;
  }
  if (typeof node === 'string' && vars) {
    return node.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
  }
  return node;
};

window.genzPick = function(obj, lang){
  if (!obj) return '';
  return obj[lang] || obj.en || '';
};
